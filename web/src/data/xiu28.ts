export function getMansionByName(name: string): Mansion {
  const found = MANSIONS.find((m) => m.name === name)
  if (!found) {
    throw new Error(`Unknown mansion name: ${name}`)
  }
  return found
}

export function getMansionById(id: string): Mansion | undefined {
  return MANSIONS.find((m) => m.id === id)
}

export function getMansionsByPalace(palace: Palace): Mansion[] {
  return MANSIONS.filter((m) => m.palace === palace)
}
